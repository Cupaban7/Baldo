/**
 * Shuffles a problem's 4 choices deterministically or randomly while keeping correctIndex synced.
 */
export function shuffleProblemChoices(
  problem: IntegralProblem,
  rng: () => number = Math.random
): IntegralProblem {
  const indexed = problem.choices.map((text, idx) => ({
    text,
    isCorrect: idx === problem.correctIndex,
  }));
  for (let i = indexed.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [indexed[i], indexed[j]] = [indexed[j], indexed[i]];
  }
  const newCorrectIndex = indexed.findIndex((item) => item.isCorrect);
  return {
    ...problem,
    choices: [
      indexed[0].text,
      indexed[1].text,
      indexed[2].text,
      indexed[3].text,
    ],
    correctIndex: newCorrectIndex,
  };
}

/**
 * Draws `count` non-repeating problems for a notebook from the requested difficulty pool.
 */
export function drawNotebookProblems(
  difficulty: Difficulty,
  usedIds: Set<string>,
  count = 3,
  rng: () => number = Math.random
): IntegralProblem[] {
  const pool = INTEGRAL_PROBLEMS.filter((p) => p.difficulty === difficulty);
  let available = pool.filter((p) => !usedIds.has(p.id));
  if (available.length < count) {
    // Fallback if pool exhausted
    available = [...pool];
  }
  const copy = [...available];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  const picked = copy.slice(0, count).map((p) => {
    usedIds.add(p.id);
    return shuffleProblemChoices(p, rng);
  });
  return picked;
}
